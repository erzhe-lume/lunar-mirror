export const MINOR_ARCANA: TarotCard[] = MINOR_SEEDS.map(
  ([suitIndex, rank, uprightKeywords, uprightMeaning, reversedKeywords, reversedMeaning], index) => {
    const suit = SUITS[suitIndex]
    const name =
      rank === 1 ? `${suit.name}王牌` : `${suit.name}${RANK_CN[rank]}`
    return {
      id: 22 + index,
      roman: RANK_ROMAN[rank],
      name,
      nameEn: `${RANK_EN[rank]} of ${suit.en}`,
      symbol: suit.symbol,
      upright: { keywords: uprightKeywords, meaning: uprightMeaning },
      reversed: { keywords: reversedKeywords, meaning: reversedMeaning },
      prompts: [
        suit.prompts[(rank + suitIndex) % suit.prompts.length],
        RANK_PROMPTS[rank - 1],
      ],
    }
  },
)

