export function pickSafetyComfort(kind: SafetyKind): string {
  const items = SAFETY_COPY[kind].comforts
  return items[Math.floor(Math.random() * items.length)]
}

export function safetyOpening(kind: SafetyKind, querent?: string): string {
  const content = SAFETY_COPY[kind]
  const who = querent
    ? `如果这是替「${querent}」问的，请先确认对方和周围人的安全。\n\n`
    : ''
  const steps = [
    content.steps[0],
    content.steps[1],
    content.steps[content.steps.length - 1],
  ].filter(Boolean)
  return `${who}${pickSafetyComfort(kind)}\n\n${content.lead}\n\n${[...new Set(steps)].join('\n\n')}`
}

export function safetyReply(kind: SafetyKind): string {
  return `${pickSafetyComfort(kind)}\n\n${SAFETY_COPY[kind].reply}`
}

export function safetyInsight(kind: SafetyKind): Insight {
  return { ...SAFETY_COPY[kind].insight, crisis: true }
}

export function safetySuggestions(kind: SafetyKind): string[] {
  return [...SAFETY_COPY[kind].suggestions]
}

export function safetyRevisit(kind: SafetyKind, answer: string): string {
  const content = SAFETY_COPY[kind]
  const quoted = answer.trim().replace(/[。！？!?；;，,、\s]+$/, '')
  const echo = quoted ? ` 你这次写道：${quoted}。` : ''
  return `你此刻的安全仍然最重要。${pickSafetyComfort(kind)}${echo} ${content.close} 如果危险仍在，请拨打 110 / 120，或联系 12356 与当地援助。`
}
